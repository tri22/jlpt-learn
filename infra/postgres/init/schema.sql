BEGIN;

DROP TABLE IF EXISTS attempt_answers CASCADE;
DROP TABLE IF EXISTS exam_attempts CASCADE;
DROP TABLE IF EXISTS question_media CASCADE;
DROP TABLE IF EXISTS question_answers CASCADE;
DROP TABLE IF EXISTS media CASCADE;
DROP TABLE IF EXISTS exam_questions CASCADE;
DROP TABLE IF EXISTS question_choices CASCADE;
DROP TABLE IF EXISTS questions CASCADE;
DROP TABLE IF EXISTS sections CASCADE;
DROP TABLE IF EXISTS examinations CASCADE;
DROP TABLE IF EXISTS exam_types CASCADE;
DROP TABLE IF EXISTS levels CASCADE;
DROP TABLE IF EXISTS role_permissions CASCADE;
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS permissions CASCADE;
DROP TABLE IF EXISTS roles CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;

-- ---------- Accounts and authorization ----------

CREATE TABLE accounts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid UNIQUE NOT NULL,
    username      varchar UNIQUE NOT NULL,
    password_hash varchar NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   uuid UNIQUE NOT NULL,
    account_id  bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name        varchar,
    email       varchar,
    other_info  text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE roles (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid UNIQUE NOT NULL,
    name      varchar UNIQUE NOT NULL
);

CREATE TABLE permissions (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid UNIQUE NOT NULL,
    code      varchar UNIQUE NOT NULL,
    name      varchar
);

CREATE TABLE user_roles (
    user_id  bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id  bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE role_permissions (
    role_id        bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id  bigint NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

-- ---------- Catalog and exams ----------

CREATE TABLE levels (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    uuid UNIQUE NOT NULL,
    exam_type_id bigint NOT NULL,
    code         varchar NOT NULL,
    name         varchar NOT NULL,
    ord          int NOT NULL,
    UNIQUE (exam_type_id, code)
);

CREATE TABLE exam_types (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid UNIQUE NOT NULL,
    code      varchar UNIQUE NOT NULL,
    name      varchar UNIQUE NOT NULL
);

ALTER TABLE levels
    ADD CONSTRAINT levels_exam_type_fk
    FOREIGN KEY (exam_type_id) REFERENCES exam_types(id);

CREATE TABLE examinations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       uuid UNIQUE NOT NULL,
    title           varchar NOT NULL,
    exam_type_id    bigint NOT NULL REFERENCES exam_types(id),
    level_id        bigint REFERENCES levels(id),
    mode            varchar NOT NULL CHECK (mode IN ('reading', 'listening', 'full', 'kanji', 'vocab', 'grammar')),
    duration_min    int NOT NULL DEFAULT 0,
    question_count  int NOT NULL DEFAULT 0,
    published       boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sections (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid UNIQUE NOT NULL,
    exam_id   bigint NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    name      varchar NOT NULL,
    ord       int NOT NULL
);

-- ---------- Questions ----------

CREATE TABLE questions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   uuid UNIQUE NOT NULL,
    content     text,
    level_id    bigint REFERENCES levels(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE question_choices (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    uuid UNIQUE NOT NULL,
    question_id  bigint NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    content      text
);

CREATE TABLE question_answers (
    question_id  bigint PRIMARY KEY REFERENCES questions(id) ON DELETE CASCADE,
    choice_id    bigint NOT NULL REFERENCES question_choices(id) ON DELETE RESTRICT
);

CREATE TABLE exam_questions (
    exam_id      bigint NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    question_id  bigint NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    position     int NOT NULL,
    section_id   bigint REFERENCES sections(id) ON DELETE SET NULL,
    PRIMARY KEY (exam_id, question_id)
);

CREATE INDEX idx_exam_questions_position ON exam_questions (exam_id, position);

-- ---------- Media ----------

CREATE TABLE media (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  uuid UNIQUE NOT NULL,
    kind       varchar NOT NULL CHECK (kind IN ('image', 'audio', 'video')),
    path       text NOT NULL,
    mime_type  varchar,
    bytes      int,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (path)
);

CREATE TABLE question_media (
    question_id  bigint NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    media_id     bigint NOT NULL REFERENCES media(id) ON DELETE CASCADE,
    ord          int NOT NULL DEFAULT 0,
    PRIMARY KEY (question_id, media_id)
);

-- ---------- Attempts ----------

CREATE TABLE exam_attempts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid UNIQUE NOT NULL,
    user_id       bigint REFERENCES users(id) ON DELETE CASCADE,
    exam_id       bigint NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    started_at    timestamptz NOT NULL DEFAULT now(),
    submitted_at  timestamptz,
    time_limit_sec   int,
    elapsed_sec      int,
    score            int,
    max_score        int,
    answered_count   int NOT NULL DEFAULT 0,
    correct_count    int NOT NULL DEFAULT 0,
    incorrect_count  int NOT NULL DEFAULT 0,
    unanswered_count int NOT NULL DEFAULT 0,
    status        varchar NOT NULL DEFAULT 'in_progress'
);

CREATE TABLE attempt_answers (
    attempt_id          bigint NOT NULL REFERENCES exam_attempts(id) ON DELETE CASCADE,
    question_id         bigint NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    selected_choice_id  bigint REFERENCES question_choices(id) ON DELETE SET NULL,
    is_correct           boolean,
    time_spent_sec       int NOT NULL DEFAULT 0 CHECK (time_spent_sec >= 0),
    selection_count      int NOT NULL DEFAULT 0 CHECK (selection_count >= 0),
    change_count         int NOT NULL DEFAULT 0 CHECK (change_count >= 0),
    PRIMARY KEY (attempt_id, question_id)
);

COMMIT;
